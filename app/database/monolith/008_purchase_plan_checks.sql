CREATE TABLE ThucKiemKeHoachMua (
 MaDot BIGINT UNSIGNED NOT NULL,
 MaDongDonMua BIGINT UNSIGNED NOT NULL,
 SoDem DECIMAL(18,3) NULL,
 ThucNhan DECIMAL(18,3) NULL,
 SoDat DECIMAL(18,3) NULL,
 SoLoi DECIMAL(18,3) NULL,
 MoTaLoi VARCHAR(5000) NULL,
 NguoiDem BIGINT UNSIGNED NULL,
 NguoiQC BIGINT UNSIGNED NULL,
 NgayDem DATETIME(6) NULL,
 NgayQC DATETIME(6) NULL,
 MaLo BIGINT UNSIGNED NULL,
 PRIMARY KEY(MaDot,MaDongDonMua),
 FOREIGN KEY(MaDot) REFERENCES DotKiemKe(MaBanGhi),
 FOREIGN KEY(MaDongDonMua) REFERENCES ChiTietDonMuaHang(MaBanGhi),
 FOREIGN KEY(MaLo) REFERENCES ChiTietLo(MaBanGhi),
 CHECK(SoDem IS NULL OR SoDem>=0),
 CHECK(ThucNhan IS NULL OR (ThucNhan>=0 AND SoDat>=0 AND SoLoi>=0 AND SoDat+SoLoi=ThucNhan))
) ENGINE=InnoDB;
