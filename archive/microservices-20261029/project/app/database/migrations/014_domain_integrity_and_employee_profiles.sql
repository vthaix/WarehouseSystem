CREATE TABLE BoPhan (
 MaBanGhi BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 Ma VARCHAR(40) NOT NULL UNIQUE, Ten VARCHAR(150) NOT NULL, MoTa TEXT NULL
);
CREATE TABLE NhanVien (
 MaNguoiDung BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 MaNhanVien VARCHAR(40) NOT NULL UNIQUE,
 MaBoPhan BIGINT UNSIGNED NULL, ChucVu VARCHAR(150) NULL,
 CONSTRAINT FK_NhanVien_NguoiDung FOREIGN KEY (MaNguoiDung) REFERENCES NguoiDung(MaBanGhi),
 CONSTRAINT FK_NhanVien_BoPhan FOREIGN KEY (MaBoPhan) REFERENCES BoPhan(MaBanGhi)
);
